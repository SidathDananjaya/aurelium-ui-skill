def render_index(directions: List[Dict[str, object]]) -> str:
    cards = []
    for direction in directions:
        light = direction["colors"]["light"]
        chips = "".join(
            '<span title="{1}" style="display:inline-block;inline-size:1.75rem;'
            "block-size:1.75rem;border-radius:4px;background:{0};"
            'border:1px solid var(--color-border)"></span>'.format(
                escape(light[key]), escape(key)
            )
            for key in ("page", "surface", "text", "accent")
        )
        cards.append(
            '<li class="panel">'
            '<h3><a href="{0}.html">{1}</a></h3>'
            "<p>{2}</p>"
            '<div style="display:flex;gap:.5rem;margin-block-start:1rem">{3}</div>'
            "</li>".format(
                escape(direction["name"]),
                escape(direction["label"]),
                escape(direction["mood"]),
                chips,
            )
        )

    first = directions[0]
    return """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Aurelium UI specimens</title>
{fonts}
<style>
{tokens}
{page}
.swatches {{ list-style: none; }}
</style>
</head>
<body>
<button class="toggle btn btn-secondary" type="button" aria-pressed="false">Dark theme</button>
<div class="wrap">
<header>
  <h1>Design direction specimens</h1>
  <p class="lede">Five complete systems. Open each to review its palette, type
  scale, surfaces, and verified contrast in both themes.</p>
</header>
<ul class="swatches">
{cards}
</ul>
</div>
<script>
{script}
</script>
</body>
</html>
""".format(
        tokens=theme_css(first),
        fonts=font_link(first["fonts"]),
        page=PAGE_CSS,
        cards="\n".join(cards),
        script=TOGGLE_SCRIPT,
    )


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        prog="build_specimens.py",
        description="Render swatch and type specimen pages for each direction.",
    )
    parser.add_argument(
        "--out", type=Path, default=OUT_DIR, help="Output directory."
    )
    args = parser.parse_args(argv)

    names = tokens_module.available_directions(DIRECTIONS_DIR)
    if not names:
        print("error: no direction files found", file=sys.stderr)
        return 2

    args.out.mkdir(parents=True, exist_ok=True)
    directions = [tokens_module.load_direction(name, DIRECTIONS_DIR) for name in names]

    for direction in directions:
        path = args.out / "{0}.html".format(direction["name"])
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(render_specimen(direction, names))
        print("wrote", path.relative_to(REPO_ROOT).as_posix())

    index_path = args.out / "index.html"
    with open(index_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(render_index(directions))
    print("wrote", index_path.relative_to(REPO_ROOT).as_posix())

    return 0


if __name__ == "__main__":
    sys.exit(main())
