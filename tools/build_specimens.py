def font_link(fonts: Dict[str, str]) -> str:
    """Build a Google Fonts link so the specimen shows the real faces.

    Without this the page falls back to a system serif, which defeats the
    purpose of a type specimen.
    """
    families = []
    seen = set()
    for role in ("display", "body", "mono"):
        family = fonts.get(role)
        if not family or family in seen:
            continue
        seen.add(family)
        weights = "300;400;500;600;700" if role != "mono" else "400;500"
        families.append(
            "family={0}:wght@{1}".format(family.replace(" ", "+"), weights)
        )
    if not families:
        return ""
    return (
        '<link rel="preconnect" href="https://fonts.googleapis.com" />\n'
        '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />\n'
        '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?{0}'
        '&amp;display=swap" />'.format("&amp;".join(families))
    )


def escape(text: str) -> str:
    return (
        str(text)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def theme_css(direction: Dict[str, object]) -> str:
    """Light by default, dark under both the media query and the data attribute."""
    built = tokens_module.build_tokens(direction, opulence=6, density=5, motion=6)
    return tokens_module.format_css(built, "auto")


def swatch_markup(colors: Dict[str, str]) -> str:
    items = []
    for name in SWATCH_ORDER:
        if name not in colors:
            continue
        items.append(
            '<li class="swatch">'
            '<div class="chip" style="background: var(--color-{0})"></div>'
            "<b>{0}</b><code>{1}</code>"
            "</li>".format(escape(name), escape(colors[name]))
        )
    return "\n".join(items)


def type_markup(fonts: Dict[str, str]) -> str:
    rows = []
    for step in TYPE_STEPS:
        display = step in ("5xl", "4xl", "3xl")
        face = ' display-face' if display else ""
        rows.append(
            '<div class="type-row">'
            "<code>{0}</code>"
            '<p class="specimen{1}" style="font-size: var(--text-{0});'
            " line-height: var(--leading-{0});"
            ' letter-spacing: var(--tracking-{0})">{2}</p>'
            "</div>".format(escape(step), face, escape(SPECIMEN_LINE))
        )
    return "\n".join(rows)


def pairs_markup(direction: Dict[str, object]) -> str:
    items = []
    for pair in direction.get("contrast_pairs", []):
        palette = direction["colors"][pair["theme"]]
        ratio = contrast_module.contrast_ratio(
            contrast_module.parse_color(palette[pair["fg"]]),
            contrast_module.parse_color(palette[pair["bg"]]),
        )
        items.append(
            "<li>{0} on {1} <em>({2})</em> "
            '<span class="ok">{3:.2f}:1</span> needs {4}:1</li>'.format(
                escape(pair["fg"]),
                escape(pair["bg"]),
                escape(pair["theme"]),
                ratio,
                pair.get("min", 4.5),
            )
        )
    return "\n".join(items)


